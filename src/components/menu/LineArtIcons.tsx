export function getGroupIcon(groupEn: string, className?: string) {
  const props = { className };
  switch (groupEn) {
    case "SUSHI":
      return <SushiIcon {...props} />;
    case "SALAD":
      return <SaladIcon {...props} />;
    case "SOUP":
      return <SoupIcon {...props} />;
    case "TREE APPETIZER":
      return <TreeAppetizerIcon {...props} />;
    case "PIZZA":
      return <PizzaIcon {...props} />;
    case "PASTA":
      return <PastaIcon {...props} />;
    case "BURGER":
      return <BurgerIcon {...props} />;
    case "BEEF MEAL":
      return <BeefMealIcon {...props} />;
    case "CHICKEN MEAL":
      return <ChickenMealIcon {...props} />;
    case "FAJITA":
      return <FajitaIcon {...props} />;
    case "FRIED CHICKEN":
      return <FriedChickenIcon {...props} />;
    case "QUESADILLA":
      return <QuesadillaIcon {...props} />;
    case "COLD DRINKS":
      return <ColdDrinksIcon {...props} />;
    case "HOT DRINKS":
      return <HotDrinksIcon {...props} />;
    case "DESSERTS":
      return <DessertsIcon {...props} />;
    case "EXTRAS & BEANS":
      return <ExtrasIcon {...props} />;
    default:
      return null;
  }
}
